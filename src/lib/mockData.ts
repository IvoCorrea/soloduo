import type { DemoProfile, ProfilePhoto } from '@/types';
import { getLoadingArtUrl } from './riot';

/**
 * PERFIS DE DEMONSTRAÇÃO — pessoas fictícias, usados até existir backend.
 * As fotos vêm de /public/demo/<slug>-<n>.jpg (geradas para o site); enquanto o arquivo
 * não existir, o componente cai para a arte do campeão. São assets do próprio site, por isso
 * já nascem 'approved' — uploads de usuários nunca recebem esse estado sem moderação real.
 */
function photos(slug: string, fallbacks: Array<[string, number]>): ProfilePhoto[] {
  return fallbacks.map(([champ, skin], i) => ({
    id: `${slug}-${i + 1}`,
    url: `/demo/${slug}-${i + 1}.jpg`,
    fallbackUrl: getLoadingArtUrl(champ, skin),
    focusX: 50,
    focusY: 30,
    status: 'approved',
  }));
}

